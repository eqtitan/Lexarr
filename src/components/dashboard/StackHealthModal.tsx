"use client";

import { useEffect, useState } from "react";

interface StackHealthReport {
  lastRunAt: string;
  timestamp: string | null;
  issueCount: number;
  cleanedCount: number;
  autoCleanup: boolean;
  staleMinutes: number;
  body: string;
}

interface StackHealthModalProps {
  open: boolean;
  onClose: () => void;
}

/**
 * Shows the full stack-healthcheck report body produced by the host cron.
 * Read-only — surfaces what the `/stack-healthcheck/latest-report.txt` file
 * already contains. No container control, no remote trigger.
 */
export default function StackHealthModal({ open, onClose }: StackHealthModalProps) {
  const [report, setReport] = useState<StackHealthReport | null | undefined>(
    undefined,
  );

  useEffect(() => {
    if (!open) return;
    setReport(undefined);
    let cancelled = false;
    fetch("/api/admin/stack-health")
      .then((r) => (r.ok ? r.json() : Promise.reject(r)))
      .then((d) => {
        if (!cancelled) setReport(d.report ?? null);
      })
      .catch(() => {
        if (!cancelled) setReport(null);
      });
    return () => {
      cancelled = true;
    };
  }, [open]);

  useEffect(() => {
    if (!open) return;
    function onKey(e: KeyboardEvent) {
      if (e.key === "Escape") onClose();
    }
    document.addEventListener("keydown", onKey);
    return () => document.removeEventListener("keydown", onKey);
  }, [open, onClose]);

  if (!open) return null;

  return (
    <div
      className="fixed inset-0 z-50 flex items-start justify-center overflow-y-auto bg-black/60 p-4 backdrop-blur-sm"
      onClick={onClose}
      role="dialog"
      aria-modal="true"
      aria-labelledby="stack-health-title"
    >
      <div
        className="my-8 w-full max-w-3xl overflow-hidden rounded-2xl bg-[var(--card)] ring-1 ring-[var(--border)] shadow-2xl shadow-black/50"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="flex items-start justify-between gap-4 border-b border-[var(--border)] px-5 py-4">
          <div>
            <h2
              id="stack-health-title"
              className="text-lg font-bold"
            >
              Stack Health Report
            </h2>
            {report && (
              <p className="mt-0.5 text-xs text-[var(--muted)]">
                Generated by host cron{" · "}
                {new Date(report.lastRunAt).toLocaleString()}
                {" · "}
                {report.issueCount === 0
                  ? "0 issues"
                  : `${report.issueCount} issue${report.issueCount === 1 ? "" : "s"}`}
                {report.cleanedCount > 0 && ` · ${report.cleanedCount} cleaned`}
              </p>
            )}
          </div>
          <button
            onClick={onClose}
            className="shrink-0 rounded-lg p-1.5 text-[var(--muted)] transition-colors hover:bg-[var(--card-hover)] hover:text-[var(--foreground)]"
            aria-label="Close"
          >
            <svg
              className="h-4 w-4"
              fill="none"
              viewBox="0 0 24 24"
              stroke="currentColor"
              strokeWidth={2}
            >
              <path
                strokeLinecap="round"
                strokeLinejoin="round"
                d="M6 18L18 6M6 6l12 12"
              />
            </svg>
          </button>
        </div>

        <div className="max-h-[70vh] overflow-y-auto p-5">
          {report === undefined ? (
            <div className="flex items-center gap-2 py-6 text-sm text-[var(--muted)]">
              <span className="h-4 w-4 animate-spin rounded-full border-2 border-[var(--accent)] border-t-transparent" />
              Loading report…
            </div>
          ) : report === null ? (
            <p className="py-6 text-sm text-[var(--danger)]">
              Couldn&apos;t load the healthcheck report. The
              {" "}
              <code className="rounded bg-[var(--background)] px-1 py-0.5">
                /stack-health
              </code>
              {" "}
              volume may not be mounted, or the host cron hasn&apos;t run yet.
            </p>
          ) : report.body.length === 0 ? (
            <p className="py-6 text-sm text-[var(--muted)]">
              Report body is empty — the cron ran but produced no output.
            </p>
          ) : (
            <pre className="whitespace-pre-wrap break-words rounded-lg bg-[var(--background)] p-4 font-mono text-xs leading-relaxed text-[var(--foreground)]">
              {report.body}
            </pre>
          )}
        </div>
      </div>
    </div>
  );
}
